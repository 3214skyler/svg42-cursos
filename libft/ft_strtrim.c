#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	size_t	i;
	size_t	j;
	char	*pt;

	if (!s1 || !set)
		return (NULL);
	i = 0;
	j = ft_strlen(s1);
	while (s1[i] && ft_strchr(set, s1[i]))
		i++;
	while (j > i && ft_strchr(set, s1[j - 1]))
		j--;
	pt = malloc(j - i + 1);
	if (!pt)
		return (NULL);
	ft_memcpy(pt, s1 + i, j - i);
	pt[j - i] = '\0';
	return (pt);
}
